class Command(BaseCommand):
    help = 'Seeds initial vehicle inventory from sample cars if database is empty.'

    def handle(self, *args, **options):
        count = 0
        for item in SAMPLE_VEHICLES:
            vid = item['id']
            defaults = {k: v for k, v in item.items() if k != 'id'}
            obj, created = Vehicle.objects.get_or_create(id=vid, defaults=defaults)
            if created:
                count += 1
                self.stdout.write(self.style.SUCCESS(f"Created vehicle #{vid}: {obj.name}"))
            else:
                self.stdout.write(f"Vehicle #{vid} already exists: {obj.name}")

        self.stdout.write(self.style.SUCCESS(f"Successfully ensured {len(SAMPLE_VEHICLES)} vehicles ({count} newly seeded)."))
